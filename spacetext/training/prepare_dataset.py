"""
SpaceText Dataset Preparation
==============================
Converts the raw aerospace_corpus.jsonl (output of Phase 1 acquisition)
into a structured HuggingFace Dataset in Alpaca instruction format, ready
for QLoRA fine-tuning with SFTTrainer / Unsloth.

Each JSONL record already contains `instruction_pairs` generated by the
pipeline's _build_instruction_pairs() method — we just need to flatten
those into a clean train/val/test split.

Output
------
  ./training_data/
    train.jsonl          — 80% of examples
    val.jsonl            — 10%
    test.jsonl           — 10%
    dataset_card.json    — stats summary

Alpaca format (each row):
  {
    "instruction": "<task prompt>",
    "input":       "",
    "output":      "<answer>",
    "task":        "categorization|summarization|path_prediction|..."
  }

Usage:
    python -m spacetext.training.prepare_dataset
    python -m spacetext.training.prepare_dataset --corpus ./corpus/aerospace_corpus.jsonl
"""

import json
import random
import argparse
import logging
from pathlib import Path
from typing import List, Dict

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
logger = logging.getLogger("spacetext.training.prepare_dataset")

# ── Alpaca system prompt ──────────────────────────────────────────────────────
SYSTEM_PROMPT = (
    "You are SpaceText, an expert aerospace and astrophysics AI assistant. "
    "You classify, summarize, and reason about technical aerospace documents "
    "including satellite systems, propulsion, guidance, structures, and missions. "
    "When summarizing, structure your output with: Key Objective, Technical Domain, and Summary."
)


def _format_alpaca(instruction: str, output: str, input_ctx: str = "") -> Dict:
    """Wrap an instruction-output pair in Alpaca/ChatML format."""
    return {
        "instruction": instruction.strip(),
        "input":       input_ctx.strip(),
        "output":      output.strip(),
        "text": (
            f"<|system|>\n{SYSTEM_PROMPT}\n"
            f"<|user|>\n{instruction.strip()}"
            + (f"\n\n{input_ctx.strip()}" if input_ctx.strip() else "")
            + f"\n<|assistant|>\n{output.strip()}"
        ),
    }


def load_corpus(corpus_path: str) -> List[Dict]:
    """Load JSONL corpus records."""
    records = []
    path = Path(corpus_path)
    if not path.exists():
        raise FileNotFoundError(f"Corpus not found: {corpus_path}")

    with open(path, encoding="utf-8") as f:
        for i, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as e:
                logger.warning(f"Skipping malformed line {i}: {e}")

    logger.info(f"Loaded {len(records):,} corpus records from {corpus_path}")
    return records


def extract_examples(records: List[Dict]) -> List[Dict]:
    """
    Flatten all instruction_pairs from corpus records into Alpaca examples.
    Also adds enriched summarization tasks grounded in full abstract text.
    """
    examples = []
    task_counts = {}

    for rec in records:
        title    = rec.get("title", "").strip()
        abstract = rec.get("abstract", "").strip()
        label    = rec.get("taxonomy_label", "General Aerospace")
        path     = rec.get("taxonomy_path", [label])
        sections = rec.get("sections", [])
        source   = rec.get("source", "")

        # ── Built-in instruction pairs from pipeline ───────────────────────
        for pair in rec.get("instruction_pairs", []):
            inst = pair.get("instruction", "").strip()
            out  = pair.get("output", "").strip()
            task = pair.get("task", "unknown")
            if inst and out and len(out) > 30:  # filter out degenerate pairs
                examples.append(_format_alpaca(inst, out))
                task_counts[task] = task_counts.get(task, 0) + 1

        # ── Enriched: Full structured summarization from abstract ──────────
        if abstract and len(abstract) > 200:
            # Build section highlights if available
            section_highlights = ""
            if sections:
                headings = [
                    s.get("heading", "").strip()
                    for s in sections[:6]
                    if s.get("heading") and s.get("section_type") not in ("references", "unknown")
                ]
                if headings:
                    section_highlights = f"\n**Key Sections**: {', '.join(headings)}"

            structured_out = (
                f"**Key Objective**: {abstract[:280].rstrip()}.\n"
                f"**Technical Domain**: {label} (Path: {' > '.join(path)})\n"
                f"**Summary**: {abstract[:700]}"
                + section_highlights
            )
            examples.append(_format_alpaca(
                instruction=(
                    f"Summarize the following aerospace research document. Provide a structured "
                    f"summary with Key Objective, Technical Domain, and a concise Summary paragraph.\n\n"
                    f"Title: {title}\n\nAbstract: {abstract[:1500]}"
                ),
                output=structured_out,
            ))
            task_counts["structured_summarization"] = task_counts.get("structured_summarization", 0) + 1

        # ── Enriched: Multi-section synthesis from PDF text ────────────────
        if sections and len(sections) >= 3:
            relevant_text = " ".join(
                s.get("text", "")[:400]
                for s in sections[:6]
                if s.get("section_type") in ("abstract", "introduction", "methodology", "results")
            ).strip()
            if relevant_text and len(relevant_text) > 300:
                synth_out = (
                    f"**Key Objective**: This paper addresses {label.lower()} research. "
                    f"{abstract[:250] if abstract else relevant_text[:250]}\n"
                    f"**Technical Domain**: {' > '.join(path)}\n"
                    f"**Summary**: {abstract[:500] if abstract else relevant_text[:500]}"
                )
                examples.append(_format_alpaca(
                    instruction=(
                        f"You are given excerpts from a technical aerospace paper: '{title}'.\n"
                        f"Synthesize the following sections into a structured technical summary "
                        f"(Key Objective, Technical Domain, Summary):\n\n{relevant_text[:1800]}"
                    ),
                    output=synth_out,
                ))
                task_counts["multi_section_synthesis"] = task_counts.get("multi_section_synthesis", 0) + 1

        # ── Enriched: Key concept extraction from abstract ─────────────────
        if abstract and len(abstract) > 100:
            examples.append(_format_alpaca(
                instruction=(
                    f"Extract the 3 most important technical concepts from the "
                    f"following aerospace document abstract.\n\nTitle: {title}\n\nAbstract: {abstract[:600]}"
                ),
                output=(
                    f"Domain: {label}\n"
                    f"Taxonomy Path: {' > '.join(path)}\n"
                    f"The document discusses: {abstract[:250]}"
                ),
            ))
            task_counts["concept_extraction"] = task_counts.get("concept_extraction", 0) + 1

        # ── Enriched: Source-aware domain classification ───────────────────
        if source and title:
            examples.append(_format_alpaca(
                instruction=(
                    f"Given this title from a {source.upper()} technical document, "
                    f"identify the aerospace domain.\n\nTitle: {title}"
                ),
                output=f"Domain: {label}\nTaxonomy Path: {' > '.join(path)}",
            ))
            task_counts["domain_classification"] = task_counts.get("domain_classification", 0) + 1

    logger.info(f"Extracted {len(examples):,} training examples from {len(records):,} records")
    logger.info(f"Task breakdown: {task_counts}")
    return examples


def split_and_save(examples: List[Dict], output_dir: str, seed: int = 42):
    """Shuffle and split into train/val/test, then save as JSONL."""
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    random.seed(seed)
    random.shuffle(examples)

    n = len(examples)
    n_train = int(n * 0.80)
    n_val   = int(n * 0.10)

    splits = {
        "train": examples[:n_train],
        "val":   examples[n_train: n_train + n_val],
        "test":  examples[n_train + n_val:],
    }

    stats = {}
    for split_name, split_data in splits.items():
        out_file = output_path / f"{split_name}.jsonl"
        with open(out_file, "w", encoding="utf-8") as f:
            for ex in split_data:
                f.write(json.dumps(ex, ensure_ascii=False) + "\n")
        stats[split_name] = len(split_data)
        logger.info(f"  {split_name:5s}: {len(split_data):,} examples → {out_file}")

    # ── Dataset card ──────────────────────────────────────────────────────────
    card = {
        "name":           "SpaceText Aerospace Instruction Dataset",
        "description":    "Instruction-tuning dataset for SLM fine-tuning on aerospace/astrophysics documents.",
        "format":         "Alpaca / ChatML",
        "system_prompt":  SYSTEM_PROMPT,
        "splits":         stats,
        "total_examples": n,
        "tasks":          [
            "categorization", "summarization", "structured_summarization",
            "multi_section_synthesis", "path_prediction",
            "concept_extraction", "domain_classification"
        ],
        "sources":        ["openalex", "nasa_news", "isro", "drdo", "arxiv", "esa"],
        "seed":           seed,
    }
    card_path = output_path / "dataset_card.json"
    with open(card_path, "w") as f:
        json.dump(card, f, indent=2)

    logger.info(f"Dataset card saved → {card_path}")
    logger.info(f"Total: {n:,} examples | Train: {stats['train']:,} | Val: {stats['val']:,} | Test: {stats['test']:,}")
    return stats


def main():
    parser = argparse.ArgumentParser(description="Prepare SpaceText SLM fine-tuning dataset")
    parser.add_argument("--corpus",     default="./corpus/aerospace_corpus.jsonl", help="Path to corpus JSONL")
    parser.add_argument("--output-dir", default="./training_data",                 help="Output directory for splits")
    parser.add_argument("--seed",       type=int, default=42,                      help="Random seed for shuffling")
    args = parser.parse_args()

    records  = load_corpus(args.corpus)
    examples = extract_examples(records)
    split_and_save(examples, args.output_dir, seed=args.seed)


if __name__ == "__main__":
    main()
