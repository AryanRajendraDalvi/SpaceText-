"""
SpaceText RAG Agent
====================
LangGraph state machine for aerospace document summarization and Q&A.

Two operating modes:
  1. summarize(topic)  — Multi-document cluster summarization (primary use case)
  2. ask(question)     — Single-question Q&A with retrieved context

FIX FLAW 7:  top_k=20 for summarization
FIX FLAW 8:  max_tokens=1500 for full summaries
FIX FLAW 9:  n_ctx=8192 for large context window
"""

import os
import logging
from typing import TypedDict, List, Optional, Tuple
from langgraph.graph import StateGraph, END

from .retriever import GarudDBRetriever
import json
from .prompts import (
    SYSTEM_PROMPT,
    SUMMARIZATION_SYSTEM_PROMPT,
    ROUTER_SYSTEM_PROMPT,
    format_rag_user_prompt,
    format_summarization_prompt,
)

logger = logging.getLogger("spacetext.rag.agent")

try:
    from llama_cpp import Llama
    LLAMA_CPP_AVAILABLE = True
except ImportError:
    LLAMA_CPP_AVAILABLE = False
    logger.warning("llama-cpp-python not found. Please install it.")


# ── State Schemas ──────────────────────────────────────────────────────────────

class QAState(TypedDict):
    question: str
    documents: List[str]
    answer: str


class SummarizationState(TypedDict):
    raw_input: str
    topic: str               # Fallback/Legacy
    source_filter: Optional[str]
    optimized_query: str     # Generated by Router
    detected_source: str     # Generated by Router
    cluster: List[Tuple[str, str]]   # list of (source, doc_text)
    structured_summary: str
    narrative_summary: str


# ── Core Agent Class ───────────────────────────────────────────────────────────

class SpaceTextAgent:
    """
    Unified RAG agent for SpaceText.
    Supports both summarization (primary) and Q&A (secondary) modes.
    """

    def __init__(
        self,
        model_path: str = "./models/spacetext-qwen-3b.gguf",
        db_path: str = "./aerospace_taxonomy.adk",
    ):
        self.model_path = model_path
        self.db_path = db_path

        # FIX FLAW 9: Singleton retriever prevents double-lock errors
        self.retriever = GarudDBRetriever(db_path=self.db_path)
        self.llm = None
        self._init_llm()

        # Build LangGraph workflows
        self.summarization_graph = self._build_summarization_graph()
        self.qa_graph = self._build_qa_graph()

    def _init_llm(self):
        if not LLAMA_CPP_AVAILABLE:
            raise RuntimeError("llama-cpp-python is required to run the local GGUF model.")

        if not os.path.exists(self.model_path):
            raise FileNotFoundError(f"Model not found at {self.model_path}. Please download it.")

        logger.info(f"Loading GGUF model from {self.model_path}...")
        
        # Param-1 has a max context of 2048. Qwen handles 8192.
        is_param = "param" in self.model_path.lower()
        ctx_size = 2048 if is_param else 8192
        
        self.llm = Llama(
            model_path=self.model_path,
            n_ctx=ctx_size,     
            n_gpu_layers=-1,    # Use GPU if available
            n_threads=4,        # Optimize for CPU
            verbose=False,
        )
        logger.info("Model loaded successfully.")

    # ── Summarization Graph ────────────────────────────────────────────────────

    def _route_query_node(self, state: SummarizationState) -> SummarizationState:
        """Acts as the front desk, routing the query and extracting metadata for GarudDB."""
        logger.info("Routing query and optimizing for GarudDB...")
        
        # If raw_input isn't provided (e.g. legacy fallback), just pass the topic through
        raw_query = state.get("raw_input") or state.get("topic")
        
        messages = [
            {"role": "system", "content": ROUTER_SYSTEM_PROMPT},
            {"role": "user", "content": raw_query}
        ]
        
        # Call the LLM with low temperature for strict JSON generation
        response = self.llm.create_chat_completion(
            messages=messages, 
            max_tokens=150, 
            temperature=0.1
        )
        
        # Fallbacks in case the LLM fails to output valid JSON
        optimized_query = raw_query
        detected_source = "all"
        
        try:
            content = response["choices"][0]["message"]["content"]
            # Sometimes models wrap JSON in markdown blocks
            if "```json" in content:
                content = content.split("```json")[1].split("```")[0].strip()
            elif "```" in content:
                content = content.split("```")[1].split("```")[0].strip()
                
            routing_data = json.loads(content)
            optimized_query = routing_data.get("optimized_query", raw_query)
            detected_source = routing_data.get("target_agency", "all")
            logger.info(f"Router optimized query: '{optimized_query}' | target_agency: '{detected_source}'")
        except Exception as e:
            logger.warning(f"Router Agent failed to output valid JSON: {e}. Falling back to raw query.")
        
        # If the user explicitly provided a source_filter via CLI, that overrides the router
        final_source = state.get("source_filter") if state.get("source_filter") else detected_source
        if final_source.lower() == "all":
            final_source = None
            
        return {
            "optimized_query": optimized_query,
            "detected_source": final_source
        }

    def _retrieve_cluster_node(self, state: SummarizationState) -> SummarizationState:
        """Retrieves a taxonomy-aware cluster of documents for the topic."""
        # Use the optimized query if the router generated it, otherwise fallback to topic
        search_query = state.get("optimized_query") or state.get("topic")
        search_source = state.get("detected_source")
        
        logger.info(f"Retrieving cluster using optimized query: '{search_query}'")
        
        # Fit documents within the context limits
        is_param = "param" in self.model_path.lower()
        max_docs = 5 if is_param else 20
        
        cluster = self.retriever.retrieve_cluster(
            topic=search_query,
            top_k=max_docs,
            source_filter=search_source,
        )
        return {"cluster": cluster}

    def _summarize_node(self, state: SummarizationState) -> SummarizationState:
        """Generates a structured + narrative summary from the document cluster."""
        logger.info(f"Summarizing {len(state['cluster'])} documents...")

        user_prompt = format_summarization_prompt(state["topic"], state["cluster"])

        messages = [
            {"role": "system", "content": SUMMARIZATION_SYSTEM_PROMPT},
            {"role": "user",   "content": user_prompt},
        ]

        response = self.llm.create_chat_completion(
            messages=messages,
            max_tokens=1500,   # FIX FLAW 8: 1500 tokens for a proper summary
            temperature=0.4,   # Increased from 0.2 to prevent looping
            top_p=0.9,
            repeat_penalty=1.05, # Safely lowered; 1.2 causes symbol collapse in Param-1
            stop=["## Key Findings:", "## Findings:", "Findings:", "## Structure:", "## Conclusion:"],
        )

        full_output = response["choices"][0]["message"]["content"].strip()

        # Split the structured and narrative parts
        # The model produces one unified output in the structured format
        # We extract both parts for display
        structured_part = full_output
        narrative_part = _extract_narrative(full_output)

        return {
            "structured_summary": structured_part,
            "narrative_summary": narrative_part,
        }

    def _build_summarization_graph(self):
        workflow = StateGraph(SummarizationState)
        workflow.add_node("route_query",      self._route_query_node)
        workflow.add_node("retrieve_cluster", self._retrieve_cluster_node)
        workflow.add_node("summarize",        self._summarize_node)
        workflow.set_entry_point("route_query")
        workflow.add_edge("route_query", "retrieve_cluster")
        workflow.add_edge("retrieve_cluster", "summarize")
        workflow.add_edge("summarize", END)
        return workflow.compile()

    def summarize(self, topic: str, source_filter: Optional[str] = None) -> dict:
        """Runs the summarization pipeline for a given topic."""
        initial = {
            "raw_input": topic,
            "topic": topic,
            "source_filter": source_filter,
            "optimized_query": "",
            "detected_source": "",
            "cluster": [],
            "structured_summary": "",
            "narrative_summary": "",
        }
        return self.summarization_graph.invoke(initial)

    def summarize_document(self, text: str, filename: str = "User Document") -> dict:
        """Directly summarizes a single provided document, bypassing GarudDB retrieval."""
        logger.info(f"Directly summarizing document: {filename}")
        state = {
            "topic": f"Analysis of {filename}",
            "source_filter": None,
            "cluster": [(filename, text)],
        }
        return self._summarize_node(state)

    # ── Q&A Graph ─────────────────────────────────────────────────────────────

    def _retrieve_qa_node(self, state: QAState) -> QAState:
        logger.info(f"Retrieving context for: '{state['question']}'")
        docs = self.retriever.retrieve(state["question"], top_k=5)
        return {"documents": docs}

    def _generate_qa_node(self, state: QAState) -> QAState:
        logger.info("Generating answer...")
        user_prompt = format_rag_user_prompt(state["question"], state["documents"])
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": user_prompt},
        ]
        response = self.llm.create_chat_completion(
            messages=messages,
            max_tokens=600,
            temperature=0.3,
            top_p=0.9,
        )
        return {"answer": response["choices"][0]["message"]["content"]}

    def _build_qa_graph(self):
        workflow = StateGraph(QAState)
        workflow.add_node("retrieve", self._retrieve_qa_node)
        workflow.add_node("generate", self._generate_qa_node)
        workflow.set_entry_point("retrieve")
        workflow.add_edge("retrieve", "generate")
        workflow.add_edge("generate", END)
        return workflow.compile()

    def ask(self, question: str) -> dict:
        """Runs the Q&A pipeline for a direct question."""
        initial = {"question": question, "documents": [], "answer": ""}
        return self.qa_graph.invoke(initial)


# ── Helpers ────────────────────────────────────────────────────────────────────

def _extract_narrative(full_output: str) -> str:
    """Extract the narrative Synthesis Summary section from the structured output."""
    lines = full_output.split("\n")
    in_section = False
    narrative_lines = []
    for line in lines:
        if "## Synthesis Summary" in line:
            in_section = True
            continue
        if in_section:
            if line.startswith("## "):
                break
            narrative_lines.append(line)
    narrative = "\n".join(narrative_lines).strip()
    return narrative if narrative else full_output[:500]


# ── Legacy entry point (for test_rag.py backward compatibility) ───────────────

def run_rag_agent(question: str):
    agent = SpaceTextAgent()
    print(f"\n--- Question ---\n{question}\n")
    result = agent.ask(question)

    print(f"--- Retrieved Documents ({len(result['documents'])}) ---")
    for doc in result["documents"]:
        print(doc)
        print("-" * 20)

    print(f"\n--- SpaceText Answer ---\n{result['answer']}\n")
    return result
